package pattern.Builder;

public class Car {

    String engine;
    String component;

    public String getEngine() {
        return engine;
    }

    public void setEngine(String engine) {
        this.engine = engine;
    }

    public String getComponent() {
        return component;
    }

    public void setComponent(String component) {
        this.component = component;
        this.component = component;
    }
}
